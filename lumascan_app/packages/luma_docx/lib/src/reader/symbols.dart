/// Symbol fonts (Wingdings, Symbol, Webdings) map letters to pictures. Phones
/// don't have these fonts, so the common characters are turned into the
/// Unicode character that looks the same.
String mapSymbolChar(int code, String? font) {
  var c = code >= 0xF000 && code <= 0xF0FF ? code - 0xF000 : code;
  final f = font?.toLowerCase() ?? '';
  if (f.startsWith('wingdings')) return _wingdings[c] ?? (code >= 0xF000 ? '□' : String.fromCharCode(c));
  if (f == 'symbol') {
    final g = _symbol[c];
    if (g != null) return g;
  }
  if (f.startsWith('webdings')) return _webdings[c] ?? '□';
  if (code >= 0xF000 && code <= 0xF0FF) return String.fromCharCode(c);
  return String.fromCharCode(code);
}

/// Bullet text in a symbol font, character by character.
String mapSymbolText(String text, String? font) {
  final f = font?.toLowerCase() ?? '';
  if (!(f.startsWith('wingdings') || f == 'symbol' || f.startsWith('webdings'))) {
    // Plain fonts: map private-use bullets that came from Symbol anyway.
    return String.fromCharCodes(text.runes.map((r) => r == 0xF0B7 ? 0x2022 : (r == 0xF0A7 ? 0x25AA : r)));
  }
  return text.runes.map((r) => mapSymbolChar(r, font)).join();
}

